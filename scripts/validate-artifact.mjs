import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import vm from "node:vm";
const root = resolve(import.meta.dirname, "..");
const source = await readFile(resolve(root, "dist/server/index.js"), "utf8");
JSON.parse(await readFile(resolve(root, "dist/.openai/hosting.json"), "utf8"));
const worker = await import(`data:text/javascript;base64,${Buffer.from(source).toString("base64")}`);
assert.equal(typeof worker.default?.fetch, "function");
const home = await worker.default.fetch(new Request("https://example.test/"), {}, {});
assert.equal(home.status, 200);
const homeText = await home.text();
assert.match(homeText, /HAMMERLIST/);
const script = homeText.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(script, "Inline application script is missing");
new vm.Script(script);
assert.match(script, /querySelectorAll/, "Selector helpers were corrupted during build");
const bad = await worker.default.fetch(new Request("https://example.test/api/recognize", { method: "POST", headers: { "content-type": "application/json" }, body: "{}" }), {}, {});
assert.equal(bad.status, 400);
const missingKey = await worker.default.fetch(new Request("https://example.test/api/recognize", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ image: "data:image/jpeg;base64,AA==" }) }), {}, {});
assert.equal(missingKey.status, 503);
console.log("HammerList worker artifact is valid");
